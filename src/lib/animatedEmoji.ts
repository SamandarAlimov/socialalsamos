/**
 * Telegram-style animated emoji support.
 *
 * Animations are served from Google's Noto Animated Emoji CDN as GIF/WebP,
 * which covers the full animated emoji set. If an emoji has no animation the
 * <AnimatedEmoji /> component transparently falls back to the native glyph.
 */

const CDN = 'https://fonts.gstatic.com/s/e/notoemoji/latest';

/** Convert an emoji string into Noto codepoint slugs (with & without FE0F). */
export function emojiCodepoints(emoji: string): string[] {
  const points = Array.from(emoji).map((c) => c.codePointAt(0)!.toString(16));
  const full = points.join('_');
  const stripped = points.filter((p) => p !== 'fe0f').join('_');
  return full === stripped ? [full] : [full, stripped];
}

/** Candidate animated GIF URLs for an emoji, ordered by likelihood. */
export function animatedEmojiUrls(emoji: string): string[] {
  return emojiCodepoints(emoji).map((cp) => `${CDN}/${cp}/512.gif`);
}

/** Lottie JSON url (used for high-fidelity large playback). */
export function lottieEmojiUrl(emoji: string): string {
  return `${CDN}/${emojiCodepoints(emoji)[0]}/lottie.json`;
}

