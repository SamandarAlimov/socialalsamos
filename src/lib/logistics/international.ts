export type InternationalServiceLevel = 'economy' | 'standard' | 'express';
export type InternationalIncoterm = 'DAP' | 'DDP';
export type LogisticsTransportMode = 'courier' | 'road' | 'air' | 'sea' | 'rail' | 'multimodal' | 'pickup';

export interface InternationalShippingQuote {
  quote_id: string;
  origin_country_code: string;
  destination_country_code: string;
  international: boolean;
  service_level: InternationalServiceLevel;
  incoterm: InternationalIncoterm;
  transport_mode: LogisticsTransportMode;
  currency: string;
  cart_value: number;
  billable_weight_kg: number;
  shipping_charge: number;
  estimated_duty: number;
  estimated_vat: number;
  customs_handling: number;
  estimated_import_charges: number;
  checkout_total: number;
  estimated_landed_total: number;
  eta_days_min: number;
  eta_days_max: number;
  estimate_only: boolean;
  customs_collected_at_checkout: boolean;
  metadata_complete: boolean;
  warnings: string[];
  expires_at?: string;
  rate_source?: string;
}

