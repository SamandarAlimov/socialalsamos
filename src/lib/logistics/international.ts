let displayNames: Intl.DisplayNames | null | undefined;

export function countryLabel(code: string) {
  try {
    if (displayNames === undefined) {
      displayNames = typeof Intl !== 'undefined' && 'DisplayNames' in Intl
        ? new Intl.DisplayNames(['uz', 'en'], { type: 'region' })
        : null;
    }
    return displayNames?.of(code) || code;
  } catch {
    return code;
  }
}

export const INTERNATIONAL_COUNTRY_OPTIONS = ISO_COUNTRY_CODES
  .map(code => ({ code, label: countryLabel(code) }))
  .sort((a, b) => a.label.localeCompare(b.label, 'uz'));

export function transportModeLabel(mode?: string | null) {
  const labels: Record<string, string> = {
    courier: 'Kuryer',
    road: 'Avtomobil',
    air: 'Avia',
    sea: 'Dengiz',
    rail: 'Temir yo‘l',
    multimodal: 'Multimodal',
    pickup: 'Olib ketish',
  };
  return labels[String(mode || '').toLowerCase()] || mode || '—';
}

export function serviceLevelLabel(level?: string | null) {
  return INTERNATIONAL_SERVICE_OPTIONS.find(item => item.id === level)?.label || level || '—';
}

export function etaLabel(quote?: Pick<InternationalShippingQuote, 'eta_days_min' | 'eta_days_max'> | null) {
  if (!quote) return '—';
  if (quote.eta_days_min === quote.eta_days_max) return `${quote.eta_days_min} kun`;
  return `${quote.eta_days_min}–${quote.eta_days_max} kun`;
}

export function normalizeInternationalQuote(value: unknown): InternationalShippingQuote | null {
  if (!value || typeof value !== 'object') return null;
  const q = value as Record<string, unknown>;
  if (!q.quote_id || !q.destination_country_code) return null;
  const num = (key: string) => Number(q[key] ?? 0);
  return {
    quote_id: String(q.quote_id),
    origin_country_code: String(q.origin_country_code || ''),
    destination_country_code: String(q.destination_country_code || ''),
    international: Boolean(q.international),
    service_level: String(q.service_level || 'standard') as InternationalServiceLevel,
    incoterm: String(q.incoterm || 'DAP') as InternationalIncoterm,
    transport_mode: String(q.transport_mode || 'multimodal') as LogisticsTransportMode,
    currency: String(q.currency || 'USD'),
    cart_value: num('cart_value'),
    billable_weight_kg: num('billable_weight_kg'),
    shipping_charge: num('shipping_charge'),
    estimated_duty: num('estimated_duty'),
    estimated_vat: num('estimated_vat'),
    customs_handling: num('customs_handling'),
    estimated_import_charges: num('estimated_import_charges'),
    checkout_total: num('checkout_total'),
    estimated_landed_total: num('estimated_landed_total'),
    eta_days_min: num('eta_days_min'),
    eta_days_max: num('eta_days_max'),
    estimate_only: Boolean(q.estimate_only),
    customs_collected_at_checkout: Boolean(q.customs_collected_at_checkout),
    metadata_complete: Boolean(q.metadata_complete),
    warnings: Array.isArray(q.warnings) ? q.warnings.map(String) : [],
    expires_at: q.expires_at ? String(q.expires_at) : undefined,
    rate_source: q.rate_source ? String(q.rate_source) : undefined,
  };
}
